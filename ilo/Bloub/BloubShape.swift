/// Bloub body colours (ported palette).
enum BloubColor: String, CaseIterable, Codable, Identifiable, Sendable {
    case ink, brown, red, orange, amber, green, turquoise, blue, violet, pink, grey, cream
    /// ilo's own brand colour — reserved for the mascot, never offered to players.
    case ilo

    /// Colours a player can pick for their own bloub.
    static var playerColors: [BloubColor] { allCases.filter { $0 != .ilo } }

    var id: String { rawValue }

    var color: Color {
        switch self {
        case .ink: Color(hex: 0x0A0A0C)
        case .brown: Color(hex: 0x8B5E3C)
        case .red: Color(hex: 0xE8483F)
        case .orange: Color(hex: 0xF08A24)
        case .amber: Color(hex: 0xF0B429)
        case .green: Color(hex: 0x3ECF8E)
        case .turquoise: Color(hex: 0x2FBFA0)
        case .blue: Color(hex: 0x3B93F0)
        case .violet: Color(hex: 0x8B5CF6)
        case .pink: Color(hex: 0xE152B0)
        case .grey: Color(hex: 0xA3A3A3)
        case .cream: Color(hex: 0xF1EFE9)
        case .ilo: Color(hex: 0x5A6BFF)
        }
    }

    /// Eye colour that reads on top of the body.
    var eyeColor: Color { self == .cream ? Color(hex: 0x0A0A0C) : .white }

    var unlockLevel: Int {
        switch self {
        case .ink, .blue, .violet, .green: 1
        case .orange, .pink: 2
        case .red, .turquoise: 4
        case .amber, .brown: 6
        case .grey: 8
        case .cream: 12
        case .ilo: 999
        }
    }
}
